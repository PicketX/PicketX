import assert from 'node:assert/strict'
import { join } from 'node:path'

export async function resourceOnboarding({ operator: p, view, origin, token, policy, facts, evidence }) {
  await p.getByRole('button', { name: 'Desired configuration', exact: true }).click()
  await p.getByRole('button', { name: 'Reload latest into editor', exact: true }).click()
  await p.getByLabel('Policy YAML').fill(policy); await p.getByLabel('Facts JSON').fill(facts)
  await p.getByLabel('Change reason', { exact: true }).fill('Configure exact existing host context')
  const seed = p.waitForResponse(r => r.url().endsWith('/console/api/v1/publication') && r.request().method() === 'PUT')
  await p.getByRole('button', { name: 'Save desired configuration', exact: true }).click()
  assert.equal((await seed).status(), 200)
  await p.getByRole('button', { name: 'Resources', exact: true }).click()
  await p.getByRole('button', { name: 'Use latest resource revision', exact: true }).click()
  await p.getByRole('button', { name: 'Create Resource', exact: true }).click()
  await p.locator('.resources-section [role="alert"]').waitFor()
  await p.waitForFunction(() => document.querySelector('.resources-section [role="alert"]') === document.activeElement)
  await p.getByLabel('Resource name', { exact: true }).fill('browser-metrics')
  await p.getByLabel('Endpoint 1 name', { exact: true }).fill('web')
  await p.getByLabel('Endpoint 1 port', { exact: true }).fill('8443')
  await p.getByLabel('Endpoint 1 addresses', { exact: true }).fill('192.0.2.100\n2001:db8::100')
  await p.getByRole('button', { name: 'Add Endpoint', exact: true }).click()
  await p.getByLabel('Endpoint 2 name', { exact: true }).fill('dns')
  await p.getByLabel('Endpoint 2 protocol', { exact: true }).selectOption('UDP')
  await p.getByLabel('Endpoint 2 port', { exact: true }).fill('5353')
  await p.getByLabel('Resource change reason', { exact: true }).fill('Browser structured resource')
  await p.setViewportSize({ width: 375, height: 812 })
  assert(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await p.screenshot({ path: join(evidence, 'resource-form-mobile.png'), fullPage: true })
  await p.getByRole('button', { name: 'Grants', exact: true }).click()
  await p.getByRole('button', { name: 'Resources', exact: true }).click()
  assert.equal(await p.getByLabel('Resource name', { exact: true }).inputValue(), 'browser-metrics')
  const headers = { Authorization: `Bearer ${token}` }
  const current = await fetch(`${origin}/api/v1/publication`, { headers })
  const doc = await current.json()
  const changed = await fetch(`${origin}/api/v1/publication`, { method: 'PUT', headers: { ...headers, 'Content-Type': 'application/json', 'If-Match': current.headers.get('etag') }, body: JSON.stringify({ policy: doc.policy, facts: doc.facts, reason: 'Concurrent resource revision' }) })
  assert.equal(changed.status, 200)
  await p.getByRole('button', { name: 'Refresh resources', exact: true }).click()
  const conflict = p.waitForResponse(r => r.url().endsWith('/console/api/v1/resources') && r.request().method() === 'POST')
  await p.getByRole('button', { name: 'Create Resource', exact: true }).click()
  assert.equal((await conflict).status(), 412)
  assert.equal(await p.getByLabel('Resource name', { exact: true }).inputValue(), 'browser-metrics')
  assert(await p.getByRole('button', { name: 'Create Resource', exact: true }).isDisabled())
  p.once('dialog', dialog => dialog.accept())
  await p.getByRole('button', { name: 'Use latest resource revision', exact: true }).click()
  const create = p.waitForResponse(r => r.url().endsWith('/console/api/v1/resources') && r.request().method() === 'POST')
  await p.getByRole('button', { name: 'Create Resource', exact: true }).click()
  const created = await create; assert.equal(created.status(), 201); const resource = await created.json()
  await p.locator(`[data-resource-id="${resource.uid}"]`).waitFor()
  await p.getByRole('button', { name: 'New Binding', exact: true }).click()
  await p.getByLabel('Binding name', { exact: true }).fill('browser-metrics-host')
  await p.getByLabel('Binding resource', { exact: true }).selectOption(resource.uid)
  await p.getByRole('checkbox', { name: 'web TCP/8443', exact: true }).check()
  await p.getByRole('checkbox', { name: 'dns UDP/5353', exact: true }).check()
  await p.getByLabel('Existing execution context', { exact: true }).selectOption(JSON.stringify(['agent-a', 'host-v1']))
  const preview = p.locator('.context-preview')
  for (const value of ['agent-a', 'host-v1', 'host-local', 'original-destination', '2001:db8::100/128', 'graceful']) assert((await preview.textContent()).includes(value))
  await p.getByLabel('Binding change reason', { exact: true }).fill('Browser exact context binding')
  assert(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await p.screenshot({ path: join(evidence, 'binding-form-mobile.png'), fullPage: true })
  const binding = p.waitForResponse(r => r.url().endsWith('/console/api/v1/bindings') && r.request().method() === 'POST')
  await p.getByRole('button', { name: 'Create Binding', exact: true }).click()
  const bound = await binding; assert.equal(bound.status(), 201); const result = await bound.json()
  await p.locator(`[data-binding-id="${result.uid}"]`).waitFor()
  const inventory = await (await fetch(`${origin}/api/v1/inventory`, { headers })).json()
  const saved = inventory.resources.find(r => r.uid === resource.uid)
  assert.deepEqual(saved.endpoints, [{ name: 'web', protocol: 'TCP', port: 8443, addresses: ['192.0.2.100', '2001:db8::100'] }, { name: 'dns', protocol: 'UDP', port: 5353 }])
  const storedBinding = inventory.bindings.find(b => b.uid === result.uid)
  assert(JSON.parse(storedBinding.enforcement).allowedDestinations.includes('2001:db8::100/128'))
  assert.equal((await (await fetch(`${origin}/api/v1/publication`, { headers })).json()).facts, facts)
  await p.setViewportSize({ width: 1440, height: 1000 }); await p.screenshot({ path: join(evidence, 'resources-desktop.png'), fullPage: true })
  await p.getByRole('button', { name: 'Grants', exact: true }).click()
  await p.getByRole('button', { name: 'Use latest Grant revision', exact: true }).click()
  await p.getByLabel('Resource', { exact: true }).selectOption(resource.uid)
  await p.getByLabel('Grant name', { exact: true }).fill('browser-onboarded-grant')
  await p.getByLabel('Source IP or CIDR', { exact: true }).fill('2001:db8::42')
  await p.getByRole('checkbox', { name: 'web TCP/8443', exact: true }).check()
  await p.getByLabel('Grant issue reason', { exact: true }).fill('Grant new resource')
  const grant = p.waitForResponse(r => r.url().endsWith('/console/api/v1/grants') && r.request().method() === 'POST')
  await p.getByRole('button', { name: 'Issue Grant', exact: true }).click()
  const granted = await grant; assert.equal(granted.status(), 201); const g = await granted.json()
  await p.locator(`[data-grant-id="${g.uid}"]`).getByRole('button', { name: 'Revoke Grant', exact: true }).click()
  await p.getByLabel('Revocation reason', { exact: true }).fill('Revoke onboarding grant')
  await p.getByRole('button', { name: 'Confirm revocation', exact: true }).click()
  await p.locator(`[data-grant-id="${g.uid}"]`).getByText('Revoked', { exact: true }).waitFor()
  await p.getByRole('button', { name: 'Resources', exact: true }).click()
  await p.getByRole('button', { name: 'New Resource', exact: true }).click()
  await p.getByLabel('Resource name', { exact: true }).fill('retained-read-failure')
  await p.route('**/console/api/v1/inventory', r => r.abort())
  await p.getByRole('button', { name: 'Refresh resources', exact: true }).click()
  await p.locator('.resources-section').getByText('Last read failed. Displayed data may be stale.', { exact: true }).waitFor()
  assert.equal(await p.getByLabel('Resource name', { exact: true }).inputValue(), 'retained-read-failure')
  await p.unroute('**/console/api/v1/inventory')
  await view.getByRole('button', { name: 'Resources', exact: true }).click()
  await view.getByRole('button', { name: 'Refresh resources', exact: true }).click()
  await view.locator(`[data-resource-id="${resource.uid}"]`).waitFor()
  assert.equal(await view.getByLabel('Resource name', { exact: true }).count(), 0)
  assert.equal(await view.getByRole('button', { name: 'Create Binding', exact: true }).count(), 0)
  assert(await view.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await view.screenshot({ path: join(evidence, 'resources-viewer-mobile.png'), fullPage: true })
  for (const path of ['resources', 'bindings']) {
    const status = await view.evaluate(async path => {
      const { csrf } = await (await fetch('/console/api/v1/session')).json()
      return (await fetch(`/console/api/v1/${path}`, { method: 'POST', headers: { 'X-CSRF-Token': csrf, 'Content-Type': 'application/json', 'If-Match': '"1"' }, body: '{}' })).status
    }, path)
    assert.equal(status, 403)
  }
  const audit = await (await fetch(`${origin}/api/v1/audit?limit=100`, { headers })).json()
  for (const reason of ['Browser structured resource', 'Browser exact context binding', 'Grant new resource', 'Revoke onboarding grant']) assert(audit.events.some(e => e.reason === reason && e.actor === 'principal:admin'))
  console.log('PASS actual browser Resource/dual-stack Endpoint → exact host Binding → Grant/revoke; CAS, audit, unchanged facts, draft/error/viewer/mobile; desired state only, not kernel application')
}
