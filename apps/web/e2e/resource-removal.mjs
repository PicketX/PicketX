import assert from 'node:assert/strict'
import { join } from 'node:path'
import { rejectedMutationReceipt } from './mutation-receipts.mjs'

export async function resourceRemoval({ p, origin, headers, referencedUID, evidence }) {
  const settled = () => p.waitForFunction(() => document.querySelector('.resources-section')?.getAttribute('aria-busy') === 'false')
  const confirm = () => p.getByRole('button', { name: 'Confirm Resource removal', exact: true })
  const ack = () => p.getByRole('checkbox', { name: 'I understand this removes only the unused Resource definition', exact: true })
  const open = uid => p.locator(`[data-resource-id="${uid}"]`).getByRole('button', { name: 'Remove Resource', exact: true }).click()
  const rebase = async () => {
    p.once('dialog', d => d.accept())
    await p.getByRole('button', { name: 'Use latest resource revision', exact: true }).click()
    await settled()
  }
  await settled()
  // Binding is gone, but the revoked Grant still pins this Resource.
  await open(referencedUID)
  await p.getByLabel('Removal reason', { exact: true }).fill('Do not cascade revoked Grant')
  await ack().check()
  const refused = p.waitForResponse(r => r.url().endsWith(`/resources/${referencedUID}/remove`))
  await confirm().click(); assert.equal((await refused).status(), 409)
  await p.getByText('Resource is still referenced. Review Grants (including revoked or expired), Denies, Bindings and HTTPRoutes before removing it.', { exact: true }).waitFor()
  assert.equal(await p.getByLabel('Removal reason', { exact: true }).inputValue(), 'Do not cascade revoked Grant')
  await p.getByRole('button', { name: 'Cancel removal', exact: true }).click()
  await p.getByLabel('Resource name', { exact: true }).fill('browser-unused')
  await p.getByLabel('Endpoint 1 name', { exact: true }).fill('web')
  await p.getByLabel('Endpoint 1 port', { exact: true }).fill('9443')
  await p.getByLabel('Resource change reason', { exact: true }).fill('Create disposable definition')
  const creation = p.waitForResponse(r => r.url().endsWith('/console/api/v1/resources') && r.request().method() === 'POST')
  await p.getByRole('button', { name: 'Create Resource', exact: true }).click()
  const created = await creation; assert.equal(created.status(), 201); const target = await created.json()
  await settled(); await open(target.uid)
  assert(await confirm().isDisabled())
  await p.getByRole('button', { name: 'Cancel removal', exact: true }).click()
  await open(target.uid)
  await p.getByLabel('Removal reason', { exact: true }).fill('Retire unused browser definition')
  await ack().check()
  const path = `/console/api/v1/resources/${target.uid}/remove`
  await rejectedMutationReceipt({ p, path: `/resources/${target.uid}/remove`, section: '.resources-section', submit: 'Confirm Resource removal', labels: ['Removal reason'] })
  await rebase(); assert.equal(await ack().isChecked(), false); await ack().check()
  await p.route(`**${path}`, route => route.fulfill({ status: 200, contentType: 'application/json', body: '{}' }))
  await confirm().click(); await p.locator('.resources-section [role="alert"]').waitFor(); await settled()
  assert(await confirm().isDisabled())
  assert.equal(await p.getByLabel('Removal reason', { exact: true }).inputValue(), 'Retire unused browser definition')
  assert((await (await fetch(`${origin}/api/v1/inventory`, { headers })).json()).resources.some(r => r.uid === target.uid))
  await p.unroute(`**${path}`); await rebase(); assert.equal(await ack().isChecked(), false); await ack().check()
  const current = await fetch(`${origin}/api/v1/publication`, { headers })
  const changed = await fetch(`${origin}/api/v1/resources`, { method: 'POST', headers: { ...headers, 'Content-Type': 'application/json', 'If-Match': current.headers.get('etag') }, body: JSON.stringify({ name: 'resource-removal-concurrent', endpoints: [{ name: 'web', protocol: 'TCP', port: 9444 }], reason: 'Advance Resource removal base' }) })
  assert.equal(changed.status, 201)
  const concurrentTarget = await changed.json()
  await p.getByRole('button', { name: 'Refresh resources', exact: true }).click(); await settled()
  const stale = p.waitForResponse(r => r.url().endsWith(path))
  await confirm().click(); assert.equal((await stale).status(), 412); await settled(); assert(await confirm().isDisabled())
  await rebase(); assert.equal(await ack().isChecked(), false)
  assert.equal(await p.getByLabel('Removal reason', { exact: true }).inputValue(), 'Retire unused browser definition')
  await p.setViewportSize({ width: 375, height: 812 })
  assert(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await p.screenshot({ path: join(evidence, 'resource-removal-mobile.png'), fullPage: true })
  await ack().check()
  const removed = p.waitForResponse(r => r.url().endsWith(path))
  await confirm().click(); assert.equal((await removed).status(), 200); await settled()
  assert.equal(await p.locator(`[data-resource-id="${target.uid}"]`).count(), 0)
  const remaining = await (await fetch(`${origin}/api/v1/inventory`, { headers })).json()
  assert(!remaining.resources.some(r => r.uid === target.uid)); assert(remaining.resources.some(r => r.uid === referencedUID))
  const audit = await (await fetch(`${origin}/api/v1/audit?limit=100`, { headers })).json()
  assert(audit.events.some(e => e.reason === 'Retire unused browser definition' && e.actor === 'principal:admin'))
  await p.setViewportSize({ width: 1440, height: 1000 })
  await p.screenshot({ path: join(evidence, 'resource-removal-desktop.png'), fullPage: true })
  // A target removed by another writer must not be replaced by its name or retried.
  await open(concurrentTarget.uid)
  await p.getByLabel('Removal reason', { exact: true }).fill('Reconcile removed target')
  await ack().check()
  const beforeExternal = await fetch(`${origin}/api/v1/inventory`, { headers })
  const external = await fetch(`${origin}/api/v1/resources/${concurrentTarget.uid}/remove`, { method: 'POST', headers: { ...headers, 'Content-Type': 'application/json', 'If-Match': beforeExternal.headers.get('etag') }, body: JSON.stringify({ reason: 'External cleanup', acknowledge_removal: true }) })
  assert.equal(external.status, 200)
  await rebase()
  await p.getByText('This Resource is absent from the draft revision. Cancel and inspect the latest inventory; a same-name replacement is a different target.', { exact: true }).waitFor()
  await ack().check(); assert(await confirm().isDisabled())
  await p.getByRole('button', { name: 'Cancel removal', exact: true }).click()
  console.log('PASS actual browser Resource create/cancel/remove; revoked Grant reference refusal, malformed receipt, stale CAS, explicit rebase and durable audit')
}
